"""Generate RESULTS.md and results/verdicts.json from the artifacts.

Verdicts are computed here, from the pass lines frozen in
PREREGISTRATION.md, never typed by hand. With no run
artifacts, generates an awaiting-runs RESULTS.md that
cannot be mistaken for results.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from verdicts import compute_verdicts

PUBLISHED = {"auc": 0.7810, "ks": 0.4196, "brier": 0.1355}
ARM_ORDER = ["control-champion", "xgboost-default", "lightgbm-default",
             "xgboost-tuned", "lightgbm-tuned", "sklearn-tuned"]
ARM_LABEL = {
    "control-champion": "Control: sklearn champion (published config)",
    "xgboost-default": "XGBoost (library defaults)",
    "lightgbm-default": "LightGBM (library defaults)",
    "xgboost-tuned": "XGBoost (tuned, 24 trials)",
    "lightgbm-tuned": "LightGBM (tuned, 24 trials)",
    "sklearn-tuned": "sklearn HGB (tuned, 24 trials, reference)",
}


def awaiting() -> str:
    (ROOT / "results").mkdir(exist_ok=True)
    (ROOT / "results" / "verdicts.json").write_text(json.dumps(
        {"H1": "NOT RUN", "H2": "NOT RUN", "H3": "NOT RUN"}, indent=1))
    return ("# Results\n\nNo measured run exists yet. The protocol is "
            "frozen in PREREGISTRATION.md; this file is generated by "
            "scripts/make_results.py and will carry the verdicts and "
            "the metric table once src/benchmark.py has run.\n")


def main() -> None:
    metrics_path = ROOT / "results" / "benchmark_metrics.json"
    if not metrics_path.exists():
        (ROOT / "RESULTS.md").write_text(awaiting())
        print("awaiting-runs RESULTS.md written")
        return
    metrics = json.loads(metrics_path.read_text())
    manifest = json.loads((ROOT / "results" / "run_manifest.json")
                          .read_text())
    gate_failed = bool(manifest.get("gate_failed"))
    verdicts = compute_verdicts(metrics, gate_failed)
    (ROOT / "results" / "verdicts.json").write_text(
        json.dumps(verdicts, indent=1))

    control = metrics["control-champion"]["metrics"]
    lines = ["# Results", "",
             "Generated by scripts/make_results.py from the recorded "
             "run artifacts. Verdicts are computed from the pass lines "
             "frozen in PREREGISTRATION.md.", "", "## Verdicts", ""]
    if gate_failed:
        lines += [
            f"- REPRODUCTION GATE FAILED: the control arm's AUC is "
            f"{control['auc']:.4f} against the published "
            f"{PUBLISHED['auc']:.4f} (delta "
            f"{control['auc'] - PUBLISHED['auc']:+.4f}, tolerance "
            f"0.005). The harness is declared broken; H1 to H3 are "
            f"NOT RUN and no challenger verdict is issued.", ""]
    else:
        xgb = metrics["xgboost-tuned"]["metrics"]
        lgb = metrics["lightgbm-tuned"]["metrics"]
        lines += [
            f"- H1 {verdicts['H1']}: XGBoost tuned test AUC "
            f"{xgb['auc']:.4f} against the champion's "
            f"{control['auc']:.4f}, a delta of "
            f"{verdicts['h1_delta_auc']:+.4f}; the frozen margin "
            f"was +0.005.",
            f"- H2 {verdicts['H2']}: LightGBM tuned test KS "
            f"{lgb['ks']:.4f} against the champion's "
            f"{control['ks']:.4f}, a delta of "
            f"{verdicts['h2_delta_ks']:+.4f}; the frozen margin "
            f"was +0.010.",
            f"- H3 {verdicts['H3']}: ranking by AUC (descending) "
            f"is {verdicts['order_by_auc']}; ranking by Brier "
            f"(ascending) is {verdicts['order_by_brier']}.", ""]
    lines += ["## Reproduction gate", "",
              f"Control AUC {control['auc']:.4f} vs published "
              f"{PUBLISHED['auc']:.4f} (delta "
              f"{control['auc'] - PUBLISHED['auc']:+.4f}); KS "
              f"{control['ks']:.4f} vs {PUBLISHED['ks']:.4f} (delta "
              f"{control['ks'] - PUBLISHED['ks']:+.4f}); Brier "
              f"{control['brier']:.4f} vs {PUBLISHED['brier']:.4f} "
              f"(delta {control['brier'] - PUBLISHED['brier']:+.4f}). "
              f"Gate tolerance 0.005 on AUC: "
              f"{'FAILED' if gate_failed else 'passed'}.", "",
              "## Metrics on the frozen test split (9,000 rows)", "",
              "| Arm | AUC | KS | Gini | Brier | Fit s (median) | "
              "Score s (median) |",
              "| --- | --- | --- | --- | --- | --- | --- |"]
    for arm in ARM_ORDER:
        if arm not in metrics:
            continue
        m = metrics[arm]["metrics"]
        lines.append(
            f"| {ARM_LABEL[arm]} | {m['auc']:.4f} | {m['ks']:.4f} | "
            f"{m['gini']:.4f} | {m['brier']:.4f} | "
            f"{metrics[arm]['fit_time_median_s']:.3f} | "
            f"{metrics[arm]['score_time_median_s']:.3f} |")
    tuned = [a for a in ARM_ORDER if metrics.get(a, {}).get("tuning")]
    if tuned:
        lines += ["", "## Tuning record (equal budget, frozen)", "",
                  "| Arm | Trials | Best CV AUC | Tuning wall s | "
                  "Winning parameters |",
                  "| --- | --- | --- | --- | --- |"]
        for arm in tuned:
            t = metrics[arm]["tuning"]
            params = metrics[arm]["params"]
            lines.append(
                f"| {ARM_LABEL[arm]} | {t['n_trials']} | "
                f"{t['best_cv_auc']:.4f} | {t['wall_time_s']:.1f} | "
                f"{json.dumps(params)} |")
        lines += ["", "Full trial by trial records: "
                  "results/tuning_<arm>.json. Selection metric was "
                  "mean AUC over stratified 3-fold CV on the "
                  "training rows only; the test split was scored "
                  "exactly once per final model."]
    lines += ["", f"Machine of record and versions: "
              f"results/run_manifest.json (data SHA-256 "
              f"{manifest['data_sha256'][:12]}..., "
              f"{manifest['versions']}).", ""]
    (ROOT / "RESULTS.md").write_text("\n".join(lines))
    print("RESULTS.md written; verdicts:", verdicts)


if __name__ == "__main__":
    main()
